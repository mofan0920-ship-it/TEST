    add_heading(doc, "第一部分：修改优化后的完整行程表", level=1)
    for d in days:
        add_day_section(doc, d["date"], d["theme"], d["items"])

    doc.add_page_break()

    add_heading(doc, "第二部分：要买和预约的门票/车票清单", level=1)
